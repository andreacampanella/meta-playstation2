def main():
    print("/* SPDX-License-Identifier: MIT */\n/* Generated by tools/hudfont.py: the 5x7 HUD font, 96 glyphs of 8 rows. */")
    print("static const uint8_t hud_font[96][8] = {")
    for code in range(32, 128):
        rows = GLYPHS.get(chr(code), GLYPHS[' '])
        if code == 127:
            rows = GLYPHS[' ']
        assert len(rows) == 7 and all(len(r) == 5 for r in rows), chr(code)
        data = []
        for r in rows:
            v = 0
            for i, ch in enumerate(r):
                if ch == '#':
                    v |= 0x80 >> i
            data.append(v)
        data.append(0)
        name = chr(code) if code < 127 else 'DEL'
        if name == '\\':
            name = 'backslash'
        if name == '*':
            name = 'star'
        print("\t{ %s },\t/* %s */" % (", ".join("0x%02x" % v for v in data), name))
    print("};")


if __name__ == '__main__':
    main()
